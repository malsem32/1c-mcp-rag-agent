# -*- coding: utf-8 -*-
from pathlib import Path

p = Path(__file__).resolve().parents[1] / "tools" / "agent_capabilities.py"
t = p.read_text(encoding="utf-8")
start = t.find('            "### Как лучше спрашивать"')
end = t.find('            "Спросите задачу своими словами')
if start < 0 or end < 0 or end <= start:
    raise SystemExit(f"markers not found start={start} end={end}")
new_block = """            \"### Как лучше спрашивать\",
            \"  • Период: «за прошлый год», «январь–март», «этот и прошлый год», «за все время»\",
            \"  • Excel: «в excel» / «с графиками» / «отчёт с графиком» (сам соберёт файл)\",
            \"  • После таблицы: «запихни в отчёт» / «в excel» — без повторных вопросов\",
            \"  • 2D: «продажи по контрагенту и номенклатуре за год»\",
            \"  • Уточнение: «только [контрагент]», «документы по …»\",
            \"  • Имена объектов — только из вашей CF (resolve), не из другой базы\",
            \"  • Не «подождите» — сразу tool и факты\",
            \"\",
            \"### Живые примеры\",
            \"  • «продажи по контрагентам за прошлый год в excel с графиками»\",
            \"  • «остатки товаров на складах» → «в excel»\",
            \"  • «по каким регистрам проводится [ваш документ]»\",
            \"  • «маржа по менеджерам за прошлый год»\",
            \"  • «откуда данные в форме документа …»\",
            \"\",
"""
p.write_text(t[:start] + new_block + t[end:], encoding="utf-8")
print("patched OK")
