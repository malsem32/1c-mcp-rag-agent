def main() -> int:
    ok = 0
    t = time.time()
    for q, exp in CASES:
        r = resolve_full_name(q)
        hit = r["full_name"] == exp
        top3 = [c["full_name"] for c in r["candidates"][:3]]
        ok += hit
        print("OK " if hit else ("t3 " if exp in top3 else "BAD"), q, "->", r["full_name"], r["confident"], "" if hit else top3)
    print(f"hit@1 {ok}/{len(CASES)}  ({time.time() - t:.1f}s)")
    return 0


