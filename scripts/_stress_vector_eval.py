def _hit(m: dict, subs: list[str]) -> bool:
    blob = (" ".join(str(m.get(k) or "") for k in ("path", "object_name", "location")) + " " + " ".join(map(str, m.get("proc_names") or []))).replace("\\", "/").lower()
    return any(s.lower() in blob for s in subs)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--k", type=int, default=10)
    ap.add_argument("--modes", default="hybrid,semantic,exact")
    a = ap.parse_args()
    from config import load_config
    from vector.search import search_code_vectors

    cfg = load_config()
    modes = a.modes.split(",")
    rows = []
    agg = {m: {"hit1": 0, "hitk": 0, "mrr": 0.0, "ms": 0} for m in modes}
    by_type: dict = {}
    for q, subs, typ in Q:
        rec = {"q": q, "type": typ, "expect": subs}
        for mode in modes:
            t0 = time.time()
            r = search_code_vectors(q, limit=a.k, match_mode=mode, cfg=cfg)
            ms = int((time.time() - t0) * 1000)
            ms_ = r.get("matches") or []
            rank = next((i + 1 for i, m in enumerate(ms_) if _hit(m, subs)), 0)
            rec[mode] = {
                "rank": rank,
                "ms": ms,
                "top3": [f"{m.get('path')}::{(m.get('proc_names') or [''])[:1]}" for m in ms_[:3]],
                "err": r.get("error"),
            }
            g = agg[mode]
            g["ms"] += ms
            if rank == 1:
                g["hit1"] += 1
            if rank:
                g["hitk"] += 1
                g["mrr"] += 1.0 / rank
            bt = by_type.setdefault((typ, mode), [0, 0])
            bt[1] += 1
            if rank:
                bt[0] += 1
        rows.append(rec)
        print(q[:60].ljust(62), " ".join(f"{m}={rec[m]['rank']}/{rec[m]['ms']}ms" for m in modes), flush=True)
    n = len(Q)
    print("\n=== summary (n=%d, k=%d) ===" % (n, a.k))
    for m in modes:
        g = agg[m]
        print(f"{m:<9} hit@1={g['hit1']/n:.2f} hit@{a.k}={g['hitk']/n:.2f} MRR={g['mrr']/n:.3f} avg={g['ms']//n}ms")
    for (typ, m), (h, t) in sorted(by_type.items()):
        print(f"  {typ:<7} {m:<9} {h}/{t}")
    (ROOT / "exports" / "stress_vector_eval.json").write_text(
        json.dumps({"rows": rows, "agg": agg}, ensure_ascii=False, indent=1), encoding="utf-8"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
