# слова класса, которые надо убрать из токенов поиска имени
CLASS_WORDS_RE = re.compile(
    "|".join(f"(?:{p})" for p, _, _ in _CLASS_PATTERNS),
    re.I,
)


def _low(s: str) -> str:
    return (s or "").lower().replace("ё", "е")


def detect_meta_class(phrase: str) -> tuple[str, str]:
    """(METADATA_TYPES-ключ, full_name-префикс) первого класса в фразе; ("", "") если нет."""
    pl = _low(phrase)
    best: tuple[int, str, str] | None = None
    for pat, mtype, prefix in _CLASS_PATTERNS:
        m = re.search(pat, pl)
        if not m:
            continue
        # самое раннее вхождение; при равной позиции — более специфичный (выше в списке)
        if best is None or m.start() < best[0]:
            best = (m.start(), mtype, prefix)
    if not best:
        return "", ""
    return best[1], best[2]


def strip_class_words(phrase: str) -> str:
    """Фраза без слов класса метаданных (для токенов поиска имени)."""
    return re.sub(r"\s+", " ", CLASS_WORDS_RE.sub(" ", _low(phrase))).strip()


def full_name_matches_class(full_name: str, prefix: str) -> bool:
    if not prefix:
        return True
    head = (full_name or "").split(".", 1)[0]
    if prefix == "Регистр":
        return head.startswith("Регистр")
    return head == prefix
